-- BankSphere Oracle schema: core records used by money-critical PL/SQL.
-- Run this script as the application schema owner in Oracle XE 21c.

CREATE TABLE customers_core (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR2(100) NOT NULL,
    email       VARCHAR2(255) NOT NULL UNIQUE
);

CREATE TABLE accounts (
    account_no   VARCHAR2(20) PRIMARY KEY,
    customer_id  NUMBER NOT NULL REFERENCES customers_core(customer_id),
    account_type VARCHAR2(20) NOT NULL
        CHECK (account_type IN ('SAVINGS', 'CHECKING', 'CURRENT')),
    balance      NUMBER(14, 2) DEFAULT 0 NOT NULL CHECK (balance >= 0),
    status       VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
        CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE transactions (
    txn_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no      VARCHAR2(20) NOT NULL REFERENCES accounts(account_no),
    txn_type        VARCHAR2(20) NOT NULL
        CHECK (txn_type IN ('DEPOSIT', 'WITHDRAW', 'TRANSFER')),
    amount          NUMBER(14, 2) NOT NULL,
    balance_after   NUMBER(14, 2) NOT NULL,
    related_account VARCHAR2(20),
    txn_date        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    status          VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE audit_log (
    log_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no   VARCHAR2(20) NOT NULL,
    action       VARCHAR2(30) NOT NULL,
    old_balance  NUMBER(14, 2) NOT NULL,
    new_balance  NUMBER(14, 2) NOT NULL,
    changed_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_accounts_customer ON accounts(customer_id);
CREATE INDEX ix_transactions_account_date ON transactions(account_no, txn_date);

COMMENT ON TABLE customers_core IS 'Relational customer identity needed by Oracle accounts.';
COMMENT ON TABLE accounts IS 'Authoritative account balances and account status.';
COMMENT ON TABLE transactions IS 'Oracle-side record of completed money movements.';
COMMENT ON TABLE audit_log IS 'Balance changes captured automatically by an account trigger.';
