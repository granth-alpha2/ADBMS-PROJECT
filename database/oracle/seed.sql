-- Generate a varied, repeatable 40-row transaction history across all accounts.
BEGIN
    FOR transaction_number IN 1..40 LOOP
        INSERT INTO transactions (
            account_no, txn_type, amount, balance_after, related_account, txn_date, status
        ) VALUES (
            'ACCT' || LPAD(TO_CHAR(MOD(transaction_number - 1, 15) + 1), 3, '0'),
            CASE MOD(transaction_number, 3)
                WHEN 0 THEN 'DEPOSIT'
                WHEN 1 THEN 'WITHDRAW'
                ELSE 'TRANSFER'
            END,
            100 + (MOD(transaction_number * 137, 40) * 25),
            (SELECT balance
               FROM accounts
              WHERE account_no = 'ACCT' || LPAD(TO_CHAR(MOD(transaction_number - 1, 15) + 1), 3, '0')),
            CASE WHEN MOD(transaction_number, 3) = 2
                 THEN 'ACCT' || LPAD(TO_CHAR(MOD(transaction_number + 4, 15) + 1), 3, '0')
            END,
            ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -MOD(transaction_number, 12))
                + MOD(transaction_number, 27),
            'COMPLETED'
        );
    END LOOP;
    COMMIT;
END;
